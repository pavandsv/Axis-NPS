// ---------------------------------------------------------------------------
// Survey dispatch log — how many surveys were SENT, per journey, channel and
// month, with delivery and click counts.
//
// This exists because a response rate needs a denominator the responses cannot
// supply. Deriving "sent" from the response count makes the rate a constant;
// the whole point of the metric is that it moves.
//
// Run: node scripts/generate-dispatch.mjs   (after generate-responses.mjs)
// ---------------------------------------------------------------------------
import { writeFileSync } from 'node:fs'
import { RESPONSES } from '../src/data/generated/responses.js'

let seed = 20260612
const rnd = () => ((seed = (seed * 1664525 + 1013904223) % 4294967296) / 4294967296)

// Response rate varies by channel and by journey — AI Call pulls better than
// email, collections worse than closure. Anchored near the client's 31%.
const CHANNEL_RATE = { Email: 0.26, WhatsApp: 0.34, 'AI Call': 0.42 }
const JOURNEY_LIFT = {
  onboarding: 1.05, sanction: 1.1, servicing: 0.95, refund: 0.85,
  closure: 1.12, noc: 0.9, collections: 0.72, digital: 0.98,
}

const cells = new Map()
for (const r of RESPONSES) {
  const key = `${r.journey}|${r.channel}|${r.month}`
  cells.set(key, (cells.get(key) || 0) + 1)
}

const rows = [...cells.entries()].map(([key, responses]) => {
  const [journey, channel, month] = key.split('|')
  const rate = Math.min(0.72, CHANNEL_RATE[channel] * (JOURNEY_LIFT[journey] || 1) * (0.9 + rnd() * 0.2))
  const sent = Math.max(responses, Math.round(responses / rate))
  const delivered = Math.round(sent * (0.93 + rnd() * 0.06))
  const clicked = Math.max(responses, Math.round(delivered * (0.4 + rnd() * 0.18)))
  return { journey, channel, month, sent, delivered, clicked, responses }
})

const total = rows.reduce((a, r) => a + r.sent, 0)
writeFileSync(new URL('../src/data/generated/dispatch.js', import.meta.url),
  `// AUTO-GENERATED by scripts/generate-dispatch.mjs — do not edit by hand.
// Surveys sent, delivered and clicked per journey x channel x month.

export const DISPATCH = ${JSON.stringify(rows)}
`)
console.log(`${rows.length} dispatch cells · ${total.toLocaleString('en-IN')} surveys sent`)
console.log(`overall response rate ${((RESPONSES.length / total) * 100).toFixed(1)}%`)
